window.I18N = I18N;

(function () {
  const STORAGE_KEY = "ufest.lang";
  const SUPPORTED   = ["ua", "es"];

  function detectLang() {
    const urlLang = new URLSearchParams(window.location.search).get("lang");
    if (urlLang && SUPPORTED.includes(urlLang)) return urlLang;
    const saved = localStorage.getItem(STORAGE_KEY);
    if (saved && SUPPORTED.includes(saved)) return saved;
    const nav = (navigator.language || navigator.userLanguage || "").toLowerCase();
    if (nav.startsWith("uk") || nav.startsWith("ru")) return "ua";
    if (nav.startsWith("es") || nav.startsWith("ca")) return "es";
    return "es";
  }

  function applyLang(lang) {
    if (!SUPPORTED.includes(lang)) lang = "es";
    const dict = I18N[lang];
    document.documentElement.lang = lang === "ua" ? "uk" : "es";

    document.querySelectorAll("[data-i18n]").forEach(el => {
      const key = el.getAttribute("data-i18n");
      if (dict[key] !== undefined) el.innerHTML = dict[key];
    });

    document.querySelectorAll("[data-i18n-attr]").forEach(el => {
      const spec = el.getAttribute("data-i18n-attr"); // "placeholder:reg.f.name"
      spec.split(",").forEach(pair => {
        const [attr, key] = pair.split(":").map(s => s.trim());
        if (dict[key] !== undefined) el.setAttribute(attr, dict[key]);
      });
    });

    const titleEl = document.querySelector("[data-i18n-title]");
    if (titleEl) {
      const key = titleEl.getAttribute("data-i18n-title");
      if (dict[key] !== undefined) document.title = dict[key];
    }

    document.querySelectorAll(".lang-switch button").forEach(btn => {
      btn.classList.toggle("is-active", btn.dataset.lang === lang);
    });

    syncLangLinks(lang);
    syncLanguageInUrl(lang);
    localStorage.setItem(STORAGE_KEY, lang);
  }

  function syncLangLinks(lang) {
    document.querySelectorAll("a[href]").forEach(link => {
      const href = link.getAttribute("href");
      if (!href || href.startsWith("#") || href.startsWith("mailto:") || href.startsWith("tel:")) return;
      try {
        const url = new URL(href, window.location.href);
        if (!url.pathname.endsWith(".html")) return;
        url.searchParams.set("lang", lang);
        link.setAttribute("href", url.pathname.split("/").pop() + "?" + url.searchParams.toString());
      } catch (e) {
        // Ignore invalid URLs
      }
    });
  }

  function syncLanguageInUrl(lang) {
    try {
      const current = new URL(window.location.href);
      current.searchParams.set("lang", lang);
      window.history.replaceState({}, "", current.pathname.split("/").pop() + "?" + current.searchParams.toString());
    } catch (e) {
      // Ignore history update issues
    }
  }

  window.UFest = window.UFest || {};
  window.UFest.applyLang = applyLang;
  window.UFest.detectLang = detectLang;

  document.addEventListener("DOMContentLoaded", () => {
    const lang = detectLang();
    applyLang(lang);

    document.querySelectorAll(".lang-switch button").forEach(btn => {
      btn.addEventListener("click", () => applyLang(btn.dataset.lang));
    });
  });
})();
